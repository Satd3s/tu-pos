import sqlite3
import os
import urllib.request
import json
import urllib.error

DB_EXTERNA_PATH = r"C:\Users\Satd3s_\.gemini\antigravity\scratch\pos-product-db\data\pos.db"

def _query_db_externa_by_code(codigo):
    if not os.path.exists(DB_EXTERNA_PATH):
        return None
    try:
        conn = sqlite3.connect(DB_EXTERNA_PATH)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        cursor.execute("SELECT barcode, name, brand, category, description, quantity FROM products WHERE barcode = ? LIMIT 1", (codigo,))
        row = cursor.fetchone()
        conn.close()
        if row:
            return dict(row)
    except Exception as e:
        print(f"[CATALOGO_INTEGRATION] Error leyendo pos.db: {e}")
    return None

def _query_db_externa_by_name(query, limit=20):
    if not os.path.exists(DB_EXTERNA_PATH):
        return []
    try:
        conn = sqlite3.connect(DB_EXTERNA_PATH)
        conn.row_factory = sqlite3.Row
        cursor = conn.cursor()
        search_term = f"%{query}%"
        cursor.execute("""
            SELECT barcode, name, brand, category FROM products 
            WHERE name LIKE ? OR brand LIKE ? OR category LIKE ?
            LIMIT ?
        """, (search_term, search_term, search_term, limit))
        rows = cursor.fetchall()
        conn.close()
        return [dict(row) for row in rows]
    except Exception as e:
        print(f"[CATALOGO_INTEGRATION] Error buscando por nombre en pos.db: {e}")
    return []

def _save_to_db_externa(barcode, name, brand, category, description, quantity):
    if not os.path.exists(DB_EXTERNA_PATH):
        return
    try:
        conn = sqlite3.connect(DB_EXTERNA_PATH)
        cursor = conn.cursor()
        cursor.execute("""
            INSERT OR IGNORE INTO products (barcode, name, brand, category, description, quantity, source)
            VALUES (?, ?, ?, ?, ?, ?, 'openfoodfacts')
        """, (barcode, name, brand, category, description, quantity))
        conn.commit()
        conn.close()
    except Exception as e:
        print(f"[CATALOGO_INTEGRATION] Error guardando en pos.db: {e}")

def _fetch_from_open_food_facts(barcode):
    url = f"https://world.openfoodfacts.org/api/v2/product/{barcode}.json"
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'TuPOS-Integration/1.0 (Windows; Python)'})
        with urllib.request.urlopen(req, timeout=3) as response:
            res_data = json.loads(response.read().decode())
            if res_data.get('status') == 1 or res_data.get('status_verbose') == 'product found':
                prod = res_data.get('product', {})
                name = prod.get('product_name')
                if not name:
                    return None
                brand = prod.get('brands', '')
                if brand and ',' in brand:
                    brand = brand.split(',')[0].strip()
                
                categories = prod.get('categories', '')
                category = 'Abarrotes'
                if categories:
                    first_cat = categories.split(',')[0].strip()
                    if first_cat:
                        # Limpiar nombre de categoría de prefijos de idioma (como es: o en:)
                        if ':' in first_cat:
                            first_cat = first_cat.split(':')[-1].strip()
                        category = first_cat.capitalize()
                
                quantity = prod.get('quantity', '')
                description = prod.get('generic_name', '')
                
                full_name = name
                if quantity and quantity not in name:
                    full_name = f"{name} {quantity}"
                
                _save_to_db_externa(barcode, full_name, brand, category, description, quantity)
                
                return {
                    'codigo': barcode,
                    'nombre': full_name,
                    'categoria': category,
                    'marca': brand
                }
    except Exception as e:
        print(f"[CATALOGO_INTEGRATION] Error consultando Open Food Facts: {e}")
    return None

def buscar_por_codigo(codigo):
    """Buscar producto en el catálogo por código de barras local o externo"""
    codigo = str(codigo).strip()
    
    # 1. Buscar en diccionario estático local
    if codigo in CATALOGO_ABARROTES:
        producto = CATALOGO_ABARROTES[codigo]
        return {
            'success': True,
            'encontrado': True,
            'data': {
                'codigo': codigo,
                'nombre': producto['nombre'],
                'categoria': producto.get('categoria', 'Abarrotes'),
                'marca': producto.get('marca', '')
            }
        }
    
    # 2. Buscar en base de datos pos.db (caché local de pos-product-db)
    cached_prod = _query_db_externa_by_code(codigo)
    if cached_prod:
        return {
            'success': True,
            'encontrado': True,
            'data': {
                'codigo': codigo,
                'nombre': cached_prod['name'],
                'categoria': cached_prod.get('category', 'Abarrotes'),
                'marca': cached_prod.get('brand', '')
            }
        }
    
    # 3. Buscar en Open Food Facts API (consulta online rápida)
    online_prod = _fetch_from_open_food_facts(codigo)
    if online_prod:
        return {
            'success': True,
            'encontrado': True,
            'data': online_prod
        }
    
    # 4. No encontrado
    return {
        'success': True,
        'encontrado': False,
        'data': {'codigo': codigo}
    }


def buscar_por_nombre(query):
    """Buscar productos por nombre parcial en catálogo estático y pos.db"""
    query_clean = query.lower().strip()
    resultados = []
    
    # 1. Buscar en catálogo estático local
    for codigo, producto in CATALOGO_ABARROTES.items():
        if (query_clean in producto['nombre'].lower() or 
            query_clean in producto.get('marca', '').lower()):
            resultados.append({
                'codigo': codigo,
                'nombre': producto['nombre'],
                'categoria': producto.get('categoria', ''),
                'marca': producto.get('marca', '')
            })
            
    # 2. Buscar en base de datos externa pos.db
    externos = _query_db_externa_by_name(query_clean, limit=(20 - len(resultados)))
    for ext_prod in externos:
        if not any(r['codigo'] == ext_prod['barcode'] for r in resultados):
            resultados.append({
                'codigo': ext_prod['barcode'],
                'nombre': ext_prod['name'],
                'categoria': ext_prod.get('category', 'Abarrotes'),
                'marca': ext_prod.get('brand', '')
            })
            
    return {
        'success': True,
        'data': resultados[:20]
    }


def obtener_estadisticas():
    """Obtener estadísticas del catálogo estático"""
    categorias = {}
    marcas = {}
    
    for producto in CATALOGO_ABARROTES.values():
        cat = producto.get('categoria', 'Sin categoría')
        marca = producto.get('marca', 'Sin marca')
        
        categorias[cat] = categorias.get(cat, 0) + 1
        marcas[marca] = marcas.get(marca, 0) + 1
    
    return {
        'success': True,
        'data': {
            'total_productos': len(CATALOGO_ABARROTES),
            'categorias': categorias,
            'marcas': marcas
        }
    }


